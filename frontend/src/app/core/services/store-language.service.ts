@Injectable({ providedIn: 'root' })
export class StoreLanguageService {
  private initialLanguage(): StoreLanguage {
    if (typeof localStorage === 'undefined') return 'en';
    try { return localStorage.getItem('wolftech.store.language') === 'ar' ? 'ar' : 'en'; } catch { return 'en'; }
  }
  readonly language = signal<StoreLanguage>(this.initialLanguage());
  t(key: string): string { return this.language() === 'ar' ? (AR[key] ?? key) : key; }
  setLanguage(language: StoreLanguage): void {
    this.language.set(language);
    try { localStorage.setItem('wolftech.store.language', language); } catch { /* non-persistent private mode */ }
  }
}

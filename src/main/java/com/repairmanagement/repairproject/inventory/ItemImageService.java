package com.repairmanagement.repairproject.inventory;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardOpenOption;
import java.util.UUID;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;

@Service
public class ItemImageService {
    private static final Logger log = LoggerFactory.getLogger(ItemImageService.class);
    private static final int MAX_BYTES = 5 * 1024 * 1024;
    private final Path storageDir;
    private final ItemRepository items;
    private final InventoryAccess access;

    public record ImageData(byte[] data, String contentType) {}
    private record ImageType(String mime, String suffix) {}

    public ItemImageService(@Value("${app.images.storage-dir:./data/item-images}") String directory,
                            ItemRepository items, InventoryAccess access) {
        this.storageDir = Path.of(directory).toAbsolutePath().normalize();
        this.items = items;
        this.access = access;
    }

    @Transactional
    public ManagerItemView upload(Long companyId, Long itemId, MultipartFile file, String actorEmail) {
        access.requireManager(companyId, actorEmail);
        Item item = lockedItem(companyId, itemId);
        if (!item.isActive()) {
            throw new ResponseStatusException(HttpStatus.CONFLICT, "Cannot upload an image to an inactive item");
        }
        if (file == null || file.isEmpty() || file.getSize() > MAX_BYTES) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Image must be nonempty and at most 5 MB");
        }
        final byte[] bytes;
        try {
            bytes = file.getBytes();
        } catch (IOException ex) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Could not read uploaded file");
        }
        if (bytes.length == 0 || bytes.length > MAX_BYTES) {
            throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "Image must be nonempty and at most 5 MB");
        }
        // Never trust client-provided extension, filename, or Content-Type.
        ImageType imageType = detectType(bytes);
        if (imageType == null) {
            throw new ResponseStatusException(HttpStatus.UNSUPPORTED_MEDIA_TYPE,
                "Only JPEG, PNG and WebP images are supported");
        }
        String filename = UUID.randomUUID() + imageType.suffix();
        Path destination = storageDir.resolve(filename);
        try {
            Files.createDirectories(storageDir);
            Files.write(destination, bytes, StandardOpenOption.CREATE_NEW);
        } catch (IOException ex) {
            deleteQuietly(filename); // a failed write can leave a partial file
            throw new ResponseStatusException(HttpStatus.INTERNAL_SERVER_ERROR, "Image storage unavailable");
        }
        String oldName = item.getImageFilename();
        // The database metadata and disk files must stay consistent if DB work rolls back.
        if (!TransactionSynchronizationManager.isSynchronizationActive()) {
            deleteQuietly(filename);
            throw new IllegalStateException("Image upload requires an active transaction");
        }
        TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
            @Override public void afterCompletion(int status) {
                if (status == TransactionSynchronization.STATUS_COMMITTED) {
                    if (oldName != null) deleteQuietly(oldName);
                } else {
                    deleteQuietly(filename);
                }
            }
        });
        item.setImage(filename, imageType.mime());
        items.flush();
        return ManagerItemView.of(item);
    }

    @Transactional(readOnly = true)
    public ImageData get(Long companyId, Long itemId) {
        access.requireActiveCompany(companyId);
        Item item = items.findByIdAndCompany_IdAndActiveTrue(itemId, companyId)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Image not found"));
        String filename = item.getImageFilename();
        if (filename == null) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Image not found");
        }
        try {
            // Filenames are generated by this service, not taken from URLs or user input.
            return new ImageData(Files.readAllBytes(safePath(filename)), item.getImageContentType());
        } catch (IOException ex) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Image not found");
        }
    }

    @Transactional
    public void remove(Long companyId, Long itemId, String actorEmail) {
        access.requireManager(companyId, actorEmail);
        Item item = lockedItem(companyId, itemId);
        String oldName = item.getImageFilename();
        if (oldName == null) return;
        item.clearImage();
        items.flush();
        TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
            @Override public void afterCommit() { deleteQuietly(oldName); }
        });
    }

    private Item lockedItem(Long companyId, Long itemId) {
        return items.lockForUpdate(companyId, itemId)
            .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Item not found"));
    }

    private Path safePath(String filename) {
        if (!filename.matches("[0-9a-f-]{36}\\.(jpg|png|webp)")) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Image not found");
        }
        Path location = storageDir.resolve(filename).normalize();
        if (!location.startsWith(storageDir)) {
            throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Image not found");
        }
        return location;
    }

    private void deleteQuietly(String filename) {
        try { Files.deleteIfExists(safePath(filename)); }
        catch (IOException | RuntimeException ex) { log.warn("Could not delete obsolete product image: {}", filename, ex); }
    }

    private static ImageType detectType(byte[] b) {
        if (b.length >= 8 && (b[0] & 255) == 137 && b[1] == 80 && b[2] == 78 && b[3] == 71
                && b[4] == 13 && b[5] == 10 && b[6] == 26 && b[7] == 10) {
            return new ImageType("image/png", ".png");
        }
        if (b.length >= 3 && (b[0] & 255) == 255 && (b[1] & 255) == 216 && (b[2] & 255) == 255) {
            return new ImageType("image/jpeg", ".jpg");
        }
        if (b.length >= 12 && b[0] == 'R' && b[1] == 'I' && b[2] == 'F' && b[3] == 'F'
                && b[8] == 'W' && b[9] == 'E' && b[10] == 'B' && b[11] == 'P') {
            return new ImageType("image/webp", ".webp");
        }
        return null;
    }
}
